export function calcStaffing(paxRaw: string | number) {
  const pax = parseInt(String(paxRaw).replace(/[^0-9]/g, ''), 10);
  if (!pax || isNaN(pax)) return null;
  let row = PAX_STAFFING.find(r => pax >= r.min && pax <= r.max);
  if (!row) { 
    row = pax < PAX_STAFFING[0].min ? PAX_STAFFING[0] : PAX_STAFFING[PAX_STAFFING.length - 1]; 
  }
  return { bartenders: String(row.bartenders), butlers: String(row.butlers) };
}
